--                    항상 "링크 사용 불가"로 뜨던 버그 수정
--
-- 문제 상황: 아직 어떤 question_sets에도 묶이지 않은 문제들은 카테고리별로
-- 묶여서 "OO 모음집"이라는 가상(폴백) 문제집으로 홈 화면에 보임. 이 가상
-- 문제집으로 궁합 테스트 링크를 만들면 set_id가 없어서(실제 question_sets
-- row가 아니므로) null로 저장되는데, ChemistryPage가 set_id 없는 링크를
-- 무조건 "만료/잘못된 링크"로 처리해버려서 이런 카테고리는 궁합 테스트가
-- 아예 동작하지 않았음.
--
-- 수정: chemistry_results에 category 컬럼을 추가. 폴백 문제집일 때는
-- set_id 대신 category를 저장해두고, 링크를 열 때 set_id가 없으면
-- category로 (아직 set에 안 묶인) 문제들을 다시 불러오도록 함.
--
-- Supabase 대시보드 > SQL Editor 에서 이 파일 전체를 붙여넣고 실행하세요.
-- ============================================================================

alter table chemistry_results add column if not exists category text;
